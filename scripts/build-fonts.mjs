/**
 * Generates `src/web/brand/fonts.generated.ts` — the Montserrat `@font-face` block with the
 * woff2 payloads inlined as base64 data URLs.
 *
 * Reads from `assets/fonts/`, which is committed. Nothing here touches the network: the fonts
 * are source, not a build-time download, so a checkout builds byte-identical output offline.
 *
 * Why inline rather than serve the files:
 *
 * `tsc` copies nothing (`rootDir: src`, no `allowJs`, no `resolveJsonModule`) and the Dockerfile
 * copies only `dist/` and `node_modules`, so a .woff2 on disk would never reach a running
 * container. Serving them from a new route is worse: the HMAC origin gate in
 * `src/server/configure.ts` sits above every path except /healthz and /readyz, so each new asset
 * path would have to be signed by the edge proxy too. Inlining keeps the sign-in page a single
 * self-contained response with zero subresource requests, which is also what lets it run under a
 * strict `default-src 'none'` CSP with `font-src data:`.
 *
 * The output is a BUILD ARTEFACT, gitignored, and regenerated by `npm run build`, `pretest` and
 * `typecheck`. The woff2 in `assets/fonts/` are the source of truth; nothing needs to be
 * committed twice, and the generated module cannot drift from the fonts it came from.
 *
 * Note for the Dockerfile: this runs inside `npm run build`, after `COPY . /app/`, so
 * `assets/fonts/` is present. It deliberately is NOT a `prepare` script -- `npm ci` runs before
 * that COPY, and a prepare hook would fail the image build looking for fonts that are not there
 * yet.
 */

import { readFile, writeFile } from 'node:fs/promises';

const FONT_DIR = new URL('../assets/fonts/', import.meta.url);
const OUT = new URL('../src/web/brand/fonts.generated.ts', import.meta.url);

/**
 * Only the three weights the page actually sets: headings at Light 300, body at Regular 400 and
 * buttons/labels at Medium 500.
 */
const WEIGHTS = [
  { weight: 300, file: 'montserrat-latin-300-normal.woff2' },
  { weight: 400, file: 'montserrat-latin-400-normal.woff2' },
  { weight: 500, file: 'montserrat-latin-500-normal.woff2' },
];

const LICENCE = [
  'Montserrat (c) 2011 The Montserrat Project Authors. SIL Open Font License 1.1 (assets/fonts/OFL.txt).',
];

async function encode({ weight, file }) {
  const bytes = await readFile(new URL(file, FONT_DIR));
  // Cheap integrity check: catches a truncated copy or a file replaced by something that is not
  // a font, either of which would ship a page whose type silently falls back to a system font.
  if (bytes.subarray(0, 4).toString('latin1') !== 'wOF2') {
    throw new Error(
      `${file}: not a woff2 (magic was ${JSON.stringify(bytes.subarray(0, 4).toString('latin1'))})`,
    );
  }
  console.warn(`  ${file}  ${bytes.length} bytes`);
  return { weight, base64: bytes.toString('base64') };
}

console.warn(`reading ${WEIGHTS.length} weights from assets/fonts/`);
const faces = await Promise.all(WEIGHTS.map(encode));

const css = faces
  .map(
    ({ weight, base64 }) =>
      `@font-face{font-family:'Montserrat';font-style:normal;font-weight:${weight};` +
      `font-display:swap;src:url(data:font/woff2;base64,${base64}) format('woff2')}`,
  )
  .join('');

const module = [
  '// GENERATED by scripts/build-fonts.mjs — do not edit. Run `npm run build:fonts` to refresh.',
  '// Source: assets/fonts/ (committed). See assets/fonts/README.md for provenance.',
  ...LICENCE.map(line => `// ${line}`),
  '',
  '/** Montserrat at Light 300, Regular 400 and Medium 500, inlined as base64 woff2. */',
  `export const FONT_FACE_CSS = ${JSON.stringify(css)};`,
  '',
].join('\n');

await writeFile(OUT, module);
console.warn(`wrote ${OUT.pathname} (${module.length} chars)`);
